#!/usr/bin/env node
/**
 * Write the per-statement question report after a statement_id backfill.
 *
 *   node .freebuff/report-statement-links.cjs [outPath]
 *
 * Read-only against the database. The "before" column is reconstructed from
 * .freebuff/statement-links.json (the proposals actually applied), so the report
 * says what this backfill changed rather than only what the table holds now.
 * Every statement is listed, including the ones with no question at all — a
 * report that hides those would read as better coverage than exists.
 */
const fs = require("node:fs");
const path = require("node:path");
const https = require("node:https");

const ROOT = path.join(__dirname, "..");
const REF = "zzliiazovezhxbmfeqco";
const TOKEN = (fs.readFileSync(path.join(__dirname, "get-keys.cjs"), "utf8").match(/sbp_[a-f0-9]+/) || [])[0];
const outPath = path.resolve(ROOT, process.argv[2] || "docs/question-statement-links.md");

function query(text) {
  return new Promise((resolve, reject) => {
    const payload = JSON.stringify({ query: text });
    const req = https.request(
      {
        hostname: "api.supabase.com",
        path: `/v1/projects/${REF}/database/query`,
        method: "POST",
        headers: {
          Authorization: `Bearer ${TOKEN}`,
          "Content-Type": "application/json",
          "Content-Length": Buffer.byteLength(payload),
        },
      },
      (res) => {
        let out = "";
        res.setEncoding("utf8");
        res.on("data", (c) => (out += c));
        res.on("end", () => {
          if (res.statusCode >= 300) return reject(new Error(`HTTP ${res.statusCode}: ${out.slice(0, 400)}`));
          try {
            resolve(JSON.parse(out));
          } catch {
            reject(new Error(`bad JSON: ${out.slice(0, 200)}`));
          }
        });
      },
    );
    req.on("error", reject);
    req.write(payload);
    req.end();
  });
}

(async () => {
  const rows = await query(`select sub.slug as subject, sub.name as subject_name, sl.level,
      t.slug as topic, t.name as topic_name, s.code, s.title,
      (select count(*) from public.questions q where q.statement_id = s.id)::int as questions
    from public.syllabus_statements s
    join public.topics t on t.id = s.topic_id
    join public.subject_levels sl on sl.id = t.subject_level_id
    join public.subjects sub on sub.id = sl.subject_id
    order by sub.slug, sl.level, t.sort_order, s.sort_order`);

  const proposals = JSON.parse(fs.readFileSync(path.join(__dirname, "statement-links.json"), "utf8")).proposals;
  const added = new Map();
  for (const p of proposals) {
    if (!p.code) continue;
    added.set(`${p.topic}|${p.code}`, (added.get(`${p.topic}|${p.code}`) || 0) + 1);
  }

  for (const r of rows) {
    r.after = Number(r.questions);
    r.before = Math.max(0, r.after - (added.get(`${r.topic}|${r.code}`) || 0));
  }

  const recovered = added.size > 0;
  if (!recovered) {
    console.warn("note: statement-links.json holds no applied proposals, so the before column equals the after column.");
  }

  const linkedBefore = rows.reduce((n, r) => n + r.before, 0);
  const linkedAfter = rows.reduce((n, r) => n + r.after, 0);
  const zeroBefore = rows.filter((r) => r.before === 0).length;
  const zeroAfter = rows.filter((r) => r.after === 0).length;

  const bySubject = new Map();
  for (const r of rows) {
    const key = `${r.subject}|${r.level}`;
    if (!bySubject.has(key)) bySubject.set(key, { name: r.subject_name, subject: r.subject, level: r.level, rows: [] });
    bySubject.get(key).rows.push(r);
  }

  const lines = [];
  lines.push("# Questions per syllabus statement");
  lines.push("");
  lines.push("Generated by `node .freebuff/report-statement-links.cjs`. Every statement is");
  lines.push("listed, including those with no question: a zero is the actionable finding, not");
  lines.push("an omission from the report.");
  lines.push("");
  if (!recovered) {
    lines.push("The before column could not be reconstructed: `statement-links.json` no longer");
    lines.push("holds the applied proposals, so every figure below is the current state.");
    lines.push("");
  }
  lines.push("## Totals");
  lines.push("");
  lines.push("| Measure | Before | After |");
  lines.push("|---|---|---|");
  lines.push(`| Linked questions | ${linkedBefore} | ${linkedAfter} |`);
  lines.push(`| Statements with at least one question | ${rows.length - zeroBefore} of ${rows.length} | ${rows.length - zeroAfter} of ${rows.length} |`);
  lines.push(`| Statements with none | ${zeroBefore} | ${zeroAfter} |`);
  lines.push("");
  lines.push("## By subject and level");
  lines.push("");
  lines.push("| Subject | Level | Statements | With questions | Questions | Mean per statement |");
  lines.push("|---|---|---|---|---|---|");
  for (const [key, group] of [...bySubject.entries()].sort((a, b) => a[1].subject.localeCompare(b[1].subject))) {
    const withQ = group.rows.filter((r) => r.after > 0).length;
    const total = group.rows.reduce((n, r) => n + r.after, 0);
    lines.push(
      `| ${group.name || group.subject} | ${group.level} | ${group.rows.length} | ${withQ} | ${total} | ${(total / group.rows.length).toFixed(2)} |`,
    );
  }
  lines.push("");

  for (const [, group] of [...bySubject.entries()].sort((a, b) => a[1].subject.localeCompare(b[1].subject))) {
    lines.push(`## ${group.name || group.subject} — ${group.level}`);
    lines.push("");
    lines.push("| Code | Statement | Questions | Topic |");
    lines.push("|---|---|---|---|");
    for (const r of group.rows) {
      const count = r.after === 0 ? "**0**" : String(r.after);
      lines.push(`| ${r.code} | ${r.title} | ${count} | ${r.topic_name || r.topic} |`);
    }
    lines.push("");
  }

  fs.writeFileSync(outPath, lines.join("\n"));
  console.log(`wrote ${path.relative(ROOT, outPath)}`);
  console.log(`  linked questions ${linkedBefore} -> ${linkedAfter}`);
  console.log(`  statements with none ${zeroBefore} -> ${zeroAfter} (of ${rows.length})`);
})().catch((e) => {
  console.error("FAIL", e.message);
  process.exit(1);
});
