#!/usr/bin/env node
/**
 * Splice the authored sections in .freebuff/content-depth-appends.cjs into the
 * current bodies of the ten deep-but-incomplete notes, check each result against
 * the notes gate, and emit a content module for .freebuff/deepen-materials.cjs.
 *
 *   node .freebuff/build-depth-appends.cjs            # report only
 *   node .freebuff/build-depth-appends.cjs --write    # also write the module
 *
 * Input is .freebuff/drafts/notes-depth-snapshot.json (taken from the live table
 * before any edit), so a re-run always starts from the same pre-edit body and
 * the append cannot be applied twice. The gate is imported rather than
 * reimplemented: a body that would not clear the bar is reported here, before
 * anything reaches the database.
 */
const fs = require("fs");
const path = require("path");
const { check, htmlCap } = require("./gate-notes-depth.cjs");
const module_ = require("./content-depth-appends.cjs");

const write = process.argv.includes("--write");
const snapshot = JSON.parse(fs.readFileSync(".freebuff/drafts/notes-depth-snapshot.json", "utf8"));
const byTopic = new Map(snapshot.rows.filter((r) => r.material_type === "notes").map((r) => [r.topic, r]));

// Statements come from the deepen-fetch output, which is the only local copy.
const statements = new Map();
for (const file of fs.readdirSync(".freebuff-tmp").filter((f) => f.startsWith("work-") && f.endsWith(".json"))) {
  for (const row of JSON.parse(fs.readFileSync(path.join(".freebuff-tmp", file), "utf8"))) {
    if (row.material_type === "notes") statements.set(row.topic, row.statements || []);
  }
}

let failed = 0;
const merged = { expectType: module_.expectType, rows: {}, titles: {} };

for (const edit of module_.edits) {
  const row = byTopic.get(edit.topic);
  if (!row) {
    console.error(`FAIL ${edit.topic}: no snapshot row for that topic`);
    failed++;
    continue;
  }
  let body = row.content;

  for (const [from, to] of edit.replace || []) {
    const hits = body.split(from).length - 1;
    if (hits !== 1) {
      console.error(`FAIL ${edit.topic}: replacement target found ${hits} times, expected 1`);
      failed++;
      continue;
    }
    body = body.replace(from, to);
  }

  if (edit.before) {
    const heading = body.match(/<h3\b[^>]*>([\s\S]*?)<\/h3>/gi) || [];
    const target = heading.find((h) => h.toLowerCase().includes(edit.before.match.toLowerCase()));
    if (!target) {
      console.error(`FAIL ${edit.topic}: no <h3> matching "${edit.before.match}"`);
      failed++;
      continue;
    }
    body = body.replace(target, `${edit.before.html.trim()}\n${target}`);
  }

  if (edit.tail) body = `${body.replace(/\s+$/, "")}\n${edit.tail.trim()}\n`;

  // Some rows carry a doubled ASCII apostrophe from an earlier seed that
  // escaped a quote twice, so "Fick''s law" and "Withering''s soup" render with
  // two marks. It is not damage the CHECK constraints can see (they look for
  // U+FFFD), so it survives every gate; normalise it to the curly apostrophe the
  // rest of the estate already uses.
  const beforeNormalise = body;
  body = body.replace(/''/g, "\u2019");
  if (body !== beforeNormalise) {
    const fixed = (beforeNormalise.match(/''/g) || []).length;
    console.log(`  normalised ${fixed} doubled apostrophe(s)`);
  }

  const candidate = { title: edit.title || row.title, content: body, statements: statements.get(edit.topic) || [] };
  const before = check({ ...candidate, content: row.content, title: row.title, statements: candidate.statements });
  const after = check(candidate);
  const n = candidate.statements.length;

  console.log(
    `\n${edit.topic}\n  title: ${JSON.stringify(row.title.slice(0, 60))} → ${JSON.stringify(edit.title)}\n` +
      `  body: ${row.content.length} → ${body.length} chars (${n} statements, cap ${htmlCap(candidate)})\n` +
      `  before: ${before.ok ? "PASS" : before.reasons.join("; ")}\n` +
      `  after:  ${after.ok ? "PASS" : after.reasons.join("; ")}`,
  );

  if (!after.ok) failed++;
  merged.rows[row.id] = body;
  merged.titles[row.id] = edit.title;
}

if (failed) {
  console.error(`\n${failed} row(s) would not clear the gate — nothing written`);
  process.exit(1);
}

if (!write) {
  console.log(`\nall ${module_.edits.length} rows pass; re-run with --write to emit the module`);
  process.exit(0);
}

const out = `.freebuff-tmp/depth-merged.cjs`;
fs.writeFileSync(
  out,
  `// Generated by .freebuff/build-depth-appends.cjs from the pre-edit snapshot plus\n// the authored sections in .freebuff/content-depth-appends.cjs. Do not hand-edit:\n// change the appends module and rebuild, or the next run will overwrite it.\nmodule.exports = ${JSON.stringify(merged, null, 2)};\n`,
);
console.log(`\nall ${module_.edits.length} rows pass → ${out}`);
