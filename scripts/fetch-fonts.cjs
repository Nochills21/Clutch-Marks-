#!/usr/bin/env node
/**
 * Download the brand fonts from Google Fonts once and emit a local @font-face
 * stylesheet (src/fonts.css + public/fonts/*.woff2).
 *
 * Why self-host: the <link> to fonts.googleapis.com was render-blocking
 * (PageSpeed: "render-blocking requests, est. savings of 1,210 ms") and added a
 * third-party chain HTML -> googleapis CSS -> gstatic woff2 -> first paint on
 * every page. Served from our own origin, the fonts arrive in parallel with the
 * HTML (via the preload hints in index.html) instead of after two extra round
 * trips, and no third-party request is made at all.
 *
 * Usage:
 *   node scripts/fetch-fonts.cjs            # (re)generate fonts.css + woff2 files
 *
 * Only the latin and latin-ext subsets are kept: unicode-range is preserved, so
 * the browser still fetches only the subsets a page actually uses. Roboto Mono
 * was dropped on purpose — the documented brand set is Fraunces + Inter +
 * JetBrains Mono (see the comment in index.html), and tailwind's mono stack
 * now leads with JetBrains Mono.
 */
const fs = require("fs");
const https = require("https");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT_DIR = path.join(ROOT, "public", "fonts");
const CSS_OUT = path.join(ROOT, "src", "fonts.css");

const CSS_URL =
  "https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght@9..144,400;9..144,500;9..144,600;9..144,700&family=Inter:wght@300;400;500;600;700&family=JetBrains+Mono:wght@400;500;600&display=swap";

// A current desktop Chrome UA: without one, fonts.googleapis.com answers with
// TTF files instead of woff2 (several times the bytes).
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36";

const KEEP_FAMILIES = new Set(["Fraunces", "Inter", "JetBrains Mono"]);
const KEEP_SUBSETS = new Set(["latin", "latin-ext"]);

function get(url, headers, asBuffer) {
  return new Promise((resolve, reject) => {
    const req = https.get(url, { headers }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        res.resume();
        get(res.headers.location, headers, asBuffer).then(resolve, reject);
        return;
      }
      if (res.statusCode !== 200) {
        res.resume();
        reject(new Error(`GET ${url} -> HTTP ${res.statusCode}`));
        return;
      }
      const chunks = [];
      res.on("data", (c) => chunks.push(c));
      res.on("end", () => resolve(asBuffer ? Buffer.concat(chunks) : Buffer.concat(chunks).toString("utf8")));
    });
    req.on("error", reject);
  });
}

(async () => {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const css = await get(CSS_URL, { "User-Agent": UA }, false);

  // Google emits `/* subset */` immediately before each @font-face block.
  const blockRe = /\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g;
  const faces = [];
  let m;
  while ((m = blockRe.exec(css)) !== null) {
    const subset = m[1];
    const block = m[2];
    const family = (block.match(/font-family:\s*'([^']+)'/) || [])[1];
    if (!family || !KEEP_FAMILIES.has(family) || !KEEP_SUBSETS.has(subset)) continue;
    const src = (block.match(/url\((https:\/\/[^)]+\.woff2)\)/) || [])[1];
    if (!src) continue;
    faces.push({
      subset,
      block,
      family,
      src,
      weight: ((block.match(/font-weight:\s*([^;]+);/) || [])[1] || "400").trim(),
      style: ((block.match(/font-style:\s*([^;]+);/) || [])[1] || "normal").trim(),
    });
  }
  if (!faces.length) throw new Error("no @font-face blocks matched — Google's CSS format changed");

  const used = new Set();
  const lines = [
    "/* GENERATED by scripts/fetch-fonts.cjs — do not hand-edit.",
    " *",
    " * Self-hosted brand fonts: downloaded from Google Fonts once so the site",
    " * makes no third-party request before first paint. Re-run:",
    " *   node scripts/fetch-fonts.cjs",
    " *",
    " * unicode-range is preserved from Google's own CSS, so browsers still fetch",
    " * only the subsets a page uses. Keep this file first in src/index.css —",
    " * CSS @import must precede other rules.",
    " */",
  ];

  let bytes = 0;
  for (const face of faces) {
    let name =
      `${face.family.replace(/[^a-z0-9]+/gi, "-").toLowerCase()}-${face.weight.replace(/\s+/g, "_")}-${face.subset}` +
      (face.style === "italic" ? "-italic" : "");
    let unique = name;
    let i = 2;
    while (used.has(unique)) unique = `${name}-${i++}`;
    used.add(unique);

    const buf = await get(face.src, { "User-Agent": UA }, true);
    bytes += buf.length;
    fs.writeFileSync(path.join(OUT_DIR, `${unique}.woff2`), buf);

    const rest = face.block
      .replace(/url\(https:\/\/[^)]+\.woff2\)/, `url('/fonts/${unique}.woff2')`)
      .replace(/^@font-face\s*\{/, "")
      .replace(/\}\s*$/, "");
    lines.push(`@font-face {${rest}}`);
  }

  fs.writeFileSync(CSS_OUT, `${lines.join("\n")}\n`);
  console.log(`wrote ${faces.length} faces (${(bytes / 1024).toFixed(0)} KiB) to public/fonts/ + src/fonts.css`);
  for (const face of faces) console.log(`  ${face.family} ${face.weight} ${face.subset}`);
})().catch((err) => {
  console.error("FAILED:", err.message);
  process.exit(1);
});
