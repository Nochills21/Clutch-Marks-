#!/usr/bin/env node
/**
 * Restore a backup written by scripts/db-backup.cjs.
 *
 * Three modes, in increasing order of danger:
 *
 *   --verify     decrypt, check the GCM tag, compare row counts to the manifest.
 *                Touches no database. Always run this first.
 *   --to-sql     emit restore.sql (schema + data). Inspect it, then run it with
 *                psql against the target. This is the disaster-recovery path.
 *   --apply      run it yourself against --database-url (needs the `pg` package).
 *
 * Usage:
 *   node scripts/db-restore.cjs backups/db/<file>.cmbackup.enc --verify
 *   node scripts/db-restore.cjs backups/db/<file>.cmbackup.enc --to-sql restore.sql
 *   node scripts/db-restore.cjs backups/db/<file>.cmbackup.enc --to-sql out.sql --tables subjects,plans
 *   node scripts/db-restore.cjs <file> --apply --database-url "postgres://..."
 *
 * BACKUP_PASSPHRASE must match the one used to make the backup.
 */
const fs = require("fs");
const zlib = require("zlib");
const crypto = require("crypto");

const BUNDLE_FORMAT = "clutchmarks-db-backup";

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i !== -1 && process.argv[i + 1] && !process.argv[i + 1].startsWith("--")
    ? process.argv[i + 1]
    : fallback;
}
function flag(name) {
  return process.argv.includes(`--${name}`);
}

// ------------------------------------------------------------------ decrypt --
function decrypt(buf, passphrase) {
  const nl = buf.indexOf(0x0a);
  if (nl === -1) throw new Error("not a backup file: no header line");
  let header;
  try {
    header = JSON.parse(buf.subarray(0, nl).toString("utf8"));
  } catch {
    throw new Error("not a backup file: header is not JSON");
  }
  if (header.alg !== "aes-256-gcm") throw new Error(`unsupported cipher: ${header.alg}`);

  const salt = Buffer.from(header.salt, "base64");
  const iv = Buffer.from(header.iv, "base64");
  const tag = Buffer.from(header.tag, "base64");
  const key = crypto.scryptSync(passphrase, salt, 32, { N: 16384, r: 8, p: 1 });

  const decipher = crypto.createDecipheriv("aes-256-gcm", key, iv);
  decipher.setAuthTag(tag);
  try {
    return Buffer.concat([decipher.update(buf.subarray(nl + 1)), decipher.final()]);
  } catch {
    // A wrong passphrase and a tampered file are indistinguishable here, and
    // both must stop the restore rather than yield half a database.
    throw new Error("decryption failed: wrong BACKUP_PASSPHRASE, or the file is corrupt/tampered");
  }
}

// --------------------------------------------------------------- restore sql --
function sqlLiteral(value) {
  // json_populate_recordset does the type work, so the only escaping needed is
  // for the JSON text itself: a dollar-quoted string makes quotes free.
  return value;
}

function generateSql(bundle, tables) {
  const out = [];
  out.push("-- Generated by scripts/db-restore.cjs");
  out.push(`-- backup:   ${bundle.createdAt}  (project ${bundle.projectRef})`);
  out.push(`-- tables:   ${tables.length}`);
  out.push("--");
  out.push("-- Restores into a Supabase project. On a plain Postgres the schema");
  out.push("-- section needs an `auth.users` stub first — see the runbook.");
  out.push("");
  out.push("begin;");
  out.push("");
  if (bundle.schema) {
    out.push("-- ─── schema (idempotent, from supabase/base.sql) ───");
    out.push(bundle.schema.trim());
    out.push("");
  }
  out.push("-- ─── data ───");
  // FKs are deferred: rows are inserted table by table in name order, which is
  // not FK order. Disabling triggers for the transaction is the standard way to
  // load a whole estate without topologically sorting it.
  out.push("set local session_replication_role = replica;");
  out.push("");

  for (const table of tables) {
    const rows = bundle.tables[table];
    if (!Array.isArray(rows) || rows.length === 0) continue;
    const tag = `$j_${crypto.randomBytes(4).toString("hex")}$`;
    const json = JSON.stringify(rows);
    if (json.includes(tag)) throw new Error(`unlucky dollar-quote collision on ${table}`);
    out.push(`-- ${table}: ${rows.length} rows`);
    out.push(
      `insert into public."${table}" overriding system value\n` +
        `  select * from json_populate_recordset(null::public."${table}", ${tag}${json}${tag});`,
    );
    out.push("");
  }

  out.push("set local session_replication_role = origin;");
  out.push("");
  out.push("commit;");
  out.push("");
  return out.join("\n");
}

// --------------------------------------------------------------------- main --
(async () => {
  const file = process.argv[2];
  if (!file || file.startsWith("--")) {
    console.error("usage: node scripts/db-restore.cjs <backup.cmbackup.enc> [--verify|--to-sql out.sql|--apply]");
    process.exit(1);
  }
  if (!fs.existsSync(file)) {
    console.error(`no such file: ${file}`);
    process.exit(1);
  }
  const passphrase = process.env.BACKUP_PASSPHRASE;
  if (!passphrase) {
    console.error("BACKUP_PASSPHRASE is not set — decryption needs the same passphrase the backup used.");
    process.exit(1);
  }

  const plain = decrypt(fs.readFileSync(file), passphrase);
  const bundle = JSON.parse(zlib.gunzipSync(plain).toString("utf8"));

  if (bundle.format !== BUNDLE_FORMAT) throw new Error(`not a ${BUNDLE_FORMAT} file: ${bundle.format}`);

  const manifest = bundle.manifest || { tables: {}, totals: {} };
  const stored = Object.keys(bundle.tables).sort();

  // Integrity: every table's rows must hash to what the backup recorded. This
  // catches a truncated or edited file, which the GCM tag cannot (it proves the
  // container is intact, not that the contents are the ones recorded).
  let mismatched = 0;
  for (const table of stored) {
    const recorded = manifest.tables[table];
    if (!recorded || recorded.rows < 0) continue;
    const hash = crypto.createHash("sha256").update(JSON.stringify(bundle.tables[table])).digest("hex");
    const countOk = bundle.tables[table].length === recorded.rows;
    if (!countOk || hash !== recorded.sha256) {
      mismatched += 1;
      console.error(`  MISMATCH ${table}: rows ${bundle.tables[table].length}/${recorded.rows}, hash ${hash === recorded.sha256 ? "ok" : "differs"}`);
    }
  }

  console.log(`backup:   ${bundle.createdAt}`);
  console.log(`project:  ${bundle.projectRef}`);
  console.log(`tables:   ${stored.length}`);
  console.log(`rows:     ${manifest.totals.rows ?? "?"}`);
  console.log(`integrity: ${mismatched === 0 ? "OK — every table matches its recorded hash" : `${mismatched} table(s) MISMATCHED`}`);

  const failedTables = Object.entries(manifest.tables).filter(([, v]) => v.rows === -1);
  if (failedTables.length) {
    console.error(`\nThis backup is INCOMPLETE — ${failedTables.length} table(s) failed to dump:`);
    for (const [t, v] of failedTables) console.error(`  ${t}: ${v.error}`);
    console.error("Restoring it would give you a database that looks healthy and is missing data.");
    process.exit(1);
  }
  if (mismatched > 0) process.exit(1);

  if (!flag("to-sql") && !flag("apply")) {
    if (flag("verify")) {
      console.log("\nverify: OK");
      return;
    }
    console.log("\nNothing written. Pass --to-sql <file> or --apply.");
    return;
  }

  const only = arg("tables", null);
  const tables = only ? only.split(",").map((t) => t.trim()).filter(Boolean) : stored;
  const unknown = tables.filter((t) => !stored.includes(t));
  if (unknown.length) {
    console.error(`unknown table(s): ${unknown.join(", ")}`);
    process.exit(1);
  }

  const restoreSql = generateSql(bundle, tables);

  if (flag("to-sql")) {
    const outFile = arg("to-sql", "restore.sql");
    fs.writeFileSync(outFile, restoreSql);
    console.log(`\nwrote ${outFile} (${(Buffer.byteLength(restoreSql) / 1024 / 1024).toFixed(1)} MB, ${tables.length} tables)`);
    console.log("Next:  psql \"$TARGET_DATABASE_URL\" -v ON_ERROR_STOP=1 -f " + outFile);
    return;
  }

  // --apply
  const url = arg("database-url", process.env.DATABASE_URL);
  if (!url) {
    console.error("--apply needs --database-url (or DATABASE_URL in the environment).");
    process.exit(1);
  }
  let pg;
  try {
    pg = require("pg");
  } catch {
    console.error("--apply needs the `pg` package (npm i pg), or use --to-sql and psql instead.");
    process.exit(1);
  }
  const client = new pg.Client({ connectionString: url });
  await client.connect();
  try {
    await client.query(restoreSql);
    console.log("\napplied.");
  } finally {
    await client.end();
  }
})().catch((err) => {
  console.error("restore failed:", err.message);
  process.exit(1);
});
